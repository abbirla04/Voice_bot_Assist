"""Generate scenarios.yaml (LiveKit Cloud simulations) from bench/scenarios.py.

    python bench/make_scenarios_yaml.py
    lk agent simulate text  --scenarios scenarios.yaml    # LLM-simulated callers, text
    lk agent simulate audio --scenarios scenarios.yaml    # same, through STT/TTS + turn-taking

The simulated caller improvises around the script, so these catch failures the fixed
scripts in bench/evaluate.py cannot. Deterministic expectations travel in `userdata`
and are enforced by `on_simulation_end` in src/agent.py.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "bench"))

from scenarios import SCENARIOS  # noqa: E402


def to_yaml_scenario(s) -> dict:
    steps = "\n".join(
        f'{i}. When the assistant replies, say (in your own words, same language): "{t}"'
        for i, t in enumerate(s.turns[1:], start=1)
    )
    who = "a caller phoning the hospital front desk"
    instructions = (
        f"PERSONA: {who} at Demo Eye and Retina Clinic, New Delhi. Speak naturally and briefly, like a real phone caller.\n"
        f'OPENING LINE: "{s.turns[0]}"\n'
        + (f"DO, IN ORDER:\n{steps}\n" if steps else "")
        + "Answer any question the assistant asks with plausible details consistent with the above. "
        "When your goal is done, say thanks and end the conversation."
    )
    userdata = {"scenario": s.id}
    if s.expect_tools:
        userdata["expect_tools"] = s.expect_tools
    forbid = [t for t in s.forbid_tools if t != "end_call"]  # simulated callers do hang up
    if forbid:
        userdata["forbid_tools"] = forbid
    if s.expect_booking is not None:
        userdata["expect_booking"] = s.expect_booking
    return {
        "label": f"{s.id} {s.title}",
        "instructions": instructions,
        "agent_expectations": " ".join(s.rubric) or "Behaves politely and correctly.",
        "tags": {"category": s.category},
        "userdata": userdata,
    }


def main() -> None:
    doc = {
        "name": "Eye clinic front desk (Clara)",
        "scenarios": [
            to_yaml_scenario(s) for s in SCENARIOS if not s.env and s.direction == "inbound"
        ],
    }
    out = ROOT / "scenarios.yaml"
    header = (
        "# GENERATED by bench/make_scenarios_yaml.py from bench/scenarios.py - edit those, then re-run.\n"
        "# Run: lk agent simulate text --scenarios scenarios.yaml\n"
        "# S08 (slow backend) and S11 (outbound dial) only run in bench/evaluate.py\n"
    )
    out.write_text(
        header + yaml.safe_dump(doc, allow_unicode=True, sort_keys=False, width=110),
        encoding="utf-8",
    )
    print(f"written {out} ({len(doc['scenarios'])} scenarios)")


if __name__ == "__main__":
    main()
